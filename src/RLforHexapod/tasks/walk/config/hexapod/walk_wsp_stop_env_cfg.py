@configclass
class WspStopRewardsCfg(RefineRewardsCfg):
    # Mean(qdot^2)/9: the prior marching trace costs about .97 rather than .19.
    # The gate uses commanded motion only, so moving/turning gets no new joint
    # motion cost and a robot cannot evade a stop command by actually moving.
    stand_joint_velocity = RewTerm(
        func=mdp.refine_stand_joint_velocity_l2, weight=-1.0,
        params={"command_name": "base_velocity", "velocity_scale": 3.0,
                "linear_command_threshold": 0.025, "yaw_command_threshold": 0.1},
    )
    # Error relative to commanded yaw permits intended turns; raw yaw speed
    # itself is not penalized. Reuse the existing GPU-safe episode diagnostics.
    yaw_error_l2 = RewTerm(
        func=mdp.refine_yaw_tracking_l2, weight=-3.0,
        params={"command_name": "base_velocity", "linear_command_threshold": 0.025,
                "yaw_command_threshold": 0.1},
    )
    lin_vel_z_l2 = RewTerm(func=mdp.lin_vel_z_l2, weight=-8.0)
    stand_posture = RewTerm(
        func=mdp.wsp_stop_stand_posture_l2, weight=-0.25,
        params={"command_name": "base_velocity", "height_command_name": "base_height",
                "angle_scale": 0.35, "linear_command_threshold": 0.025, "yaw_command_threshold": 0.1,
                "anchor_heights": WSP_STOP_ANCHOR_HEIGHTS,
                "anchor_joint_positions_rad": WSP_STOP_ANCHOR_POSITIONS,
                "anchor_joint_names": WSP_STOP_ANCHOR_JOINTS,
                "asset_cfg": SceneEntityCfg("robot", joint_names=list(WSP_STOP_ANCHOR_JOINTS), preserve_order=True)},
    )


@configclass
class WspStopCommandsCfg(CommandCfg):
    # Separate config object: neither the old tasks nor their instances change.
    # This is a sampling probability, not a guaranteed fraction in each batch.
    base_velocity = deepcopy(CommandCfg().base_velocity)
    base_velocity.rel_standing_envs = 0.30


@configclass
class HexapodWspStopEnvCfg(HexapodRefineEnvCfg):
    rewards: WspStopRewardsCfg = WspStopRewardsCfg()
    commands: WspStopCommandsCfg = WspStopCommandsCfg()
